#!/usr/bin/env node
/**
 * Mirror registry sources to the paths an ADOPTER ends up with.
 *
 * Blocks import `@/components/ecomcn/price-tag` and `@/hooks/use-order-totals`
 * — the `target` paths, not the `src/registry/**` paths they live at here.
 * A tsconfig alias can't bridge that: a TS path mapping carries only one
 * wildcard, so `@/components/ecomcn/*` -> `src/registry/ecomcn/*​/*` is not
 * expressible.
 *
 * Mirroring instead buys two things: the site compiles against the exact
 * layout adopters install, and a missing `registryDependencies` entry breaks
 * our dev server rather than someone else's project.
 *
 * The mirrors are gitignored. src/registry/** is the source of truth.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const root = process.cwd();
const banner = (from) =>
  `/* AUTO-GENERATED by scripts/sync-registry.mjs — do not edit.\n` +
  `   Source of truth: ${from} */\n\n`;

/** `@ui/x`, `@components/x`, `~/x` -> a path under src/ (or the repo root). */
function resolveTarget(target) {
  const aliases = {
    "@ui/": "src/components/ui/",
    "@components/": "src/components/",
    "@lib/": "src/lib/",
    "@hooks/": "src/hooks/",
  };
  for (const [prefix, dir] of Object.entries(aliases)) {
    if (target.startsWith(prefix)) return join(root, dir, target.slice(prefix.length));
  }
  if (target.startsWith("~/")) return join(root, target.slice(2));
  return join(root, "src", target);
}

const registryPath = resolve(root, "registry.json");
if (!existsSync(registryPath)) {
  console.error("sync-registry: registry.json not found at the repo root.");
  process.exit(1);
}

const registry = JSON.parse(readFileSync(registryPath, "utf8"));
const includes = registry.include ?? [];
const items = [...(registry.items ?? [])];

for (const include of includes) {
  const file = resolve(root, include);
  if (!existsSync(file)) {
    console.error(`sync-registry: include not found -> ${include}`);
    process.exit(1);
  }
  for (const item of JSON.parse(readFileSync(file, "utf8")).items ?? []) {
    items.push({ ...item, __dir: dirname(file) });
  }
}

let written = 0;
let skipped = 0;

for (const item of items) {
  for (const file of item.files ?? []) {
    if (!file.target) {
      skipped++;
      continue;
    }
    const from = resolve(item.__dir ?? root, file.path);
    if (!existsSync(from)) {
      console.error(`sync-registry: ${item.name} -> missing source ${file.path}`);
      process.exit(1);
    }
    const to = resolveTarget(file.target);
    const relFrom = from.replace(root + "/", "").replace(root + "\\", "");
    const next = banner(relFrom) + readFileSync(from, "utf8");

    // Only write on change, so the dev server doesn't rebuild on every start.
    if (existsSync(to) && readFileSync(to, "utf8") === next) continue;
    mkdirSync(dirname(to), { recursive: true });
    writeFileSync(to, next);
    written++;
  }
}

/**
 * Also emit the catalogue as data. Reading registry.json from a Server
 * Component works, but dynamic fs access makes the bundler trace the whole
 * project into the output — a static import costs nothing.
 */
const data = items.map((item) => ({
  name: item.name,
  type: item.type,
  title: item.title ?? item.name,
  description: item.description ?? "",
  author: item.author ?? null,
  dependencies: item.dependencies ?? [],
  registryDependencies: item.registryDependencies ?? [],
  categories: item.categories ?? [],
  files: (item.files ?? []).map((file) => {
    const from = resolve(item.__dir ?? root, file.path);
    return {
      path: file.path,
      type: file.type,
      target: file.target ?? null,
      displayPath: file.target ?? file.path,
      content: existsSync(from) ? readFileSync(from, "utf8") : "",
    };
  }),
}));

const dataPath = join(root, "src", "lib", "registry-data.json");
const nextData = JSON.stringify(data, null, 2) + "\n";
if (!existsSync(dataPath) || readFileSync(dataPath, "utf8") !== nextData) {
  mkdirSync(dirname(dataPath), { recursive: true });
  writeFileSync(dataPath, nextData);
}

console.log(
  `sync-registry: ${items.length} items, ${written} file(s) written` +
    (skipped ? `, ${skipped} skipped (no target)` : "") +
    `, registry-data.json refreshed`
);
